const translations: Record<string, Dict> = {
  en,
  "zh-cn": zhCn,
};

function resolveStrings(): Dict {
  let locale = "en";
  try {
    locale = String(moment.locale() || "en").toLowerCase();
  } catch {
    locale = "en";
  }
  if (locale.startsWith("zh")) return translations["zh-cn"];
  return translations.en;
}

// Resolved once at load, which is fine: changing the app language reloads the
// plugin anyway.
const strings: Dict = resolveStrings();

export function t(key: string, params?: Record<string, string | number>): string {
  let text = strings[key] ?? translations.en[key] ?? key;
  if (params) {
    for (const name of Object.keys(params)) {
      text = text.split(`{{${name}}}`).join(String(params[name]));
    }
  }
  return text;
}
